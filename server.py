"""HTTP boundary onto the same `QA` used by `app.py`/`cli.py` (PR12/NOTES.md §19,
folded in from PLAN_PR11). `frontend/`'s Next.js dev server calls this over
localhost — both processes call the Databricks workspace outward for generation,
embeddings, and Unity Catalog; the workspace is the backend, not this process.

Run with `uvicorn server:app --reload` (needs `DATABRICKS_HOST`/`DATABRICKS_TOKEN`/
`DATABRICKS_WAREHOUSE_ID` or `DATABRICKS_HTTP_PATH` in the environment — see
`.env.example`).

Response shape matches `GroundedAnswer` in `frontend/services/documents/types.ts`
(folded in from PLAN_PR11 D3) rather than inventing a new one, so the UI needs no
render changes from what it already expected of `grounding.ts`.
"""
from __future__ import annotations

from contextlib import asynccontextmanager
from datetime import date
from pathlib import Path

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from dotenv import load_dotenv

load_dotenv()

from preboard.handoff import handoff_target  # noqa: E402
from preboard.qa import QA, Answer, Handoff  # noqa: E402
from preboard.wiring import (  # noqa: E402
    DEFAULT_FM_ENDPOINT,
    FM_ENDPOINT_ENV,
    build_generator,
    build_miss_log,
    build_retriever,
    build_router,
    has_databricks_credentials,
)

REPO_ROOT = Path(__file__).resolve().parent
CORPUS_DIR = REPO_ROOT / "data"
DB_PATH = REPO_ROOT / "misses.db"

# PR11 B3's shape: name the dev port explicitly rather than allow_origins=["*"]
# (rejected by browsers once credentials are involved). Verified locally: `npm run
# dev` actually serves on :3000/:3001 (vinext falls back when 3000 is taken), not
# :5173 as PLAN_PR12's own diagram assumed. In this architecture the browser never
# calls this server directly, though — /api/documents/ask is a Next.js *route
# handler* making a server-to-server fetch — so CORS isn't actually load-bearing on
# the request path this PR wires up; kept as defense-in-depth / for direct testing.
FRONTEND_ORIGIN = "http://localhost:3000"


def _build_qa():
    retriever, confidence_threshold = build_retriever(CORPUS_DIR)
    router, router_threshold = build_router(CORPUS_DIR)
    miss_log = build_miss_log(DB_PATH)
    qa = QA(
        retriever=retriever,
        generator=build_generator(),
        miss_log=miss_log,
        confidence_threshold=confidence_threshold,
        router=router,
        router_threshold=router_threshold,
    )
    return qa, miss_log


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Built once at startup, not per request: EmbeddingRetriever caches chunk
    # embeddings per instance, so a fresh QA per request would re-embed the whole
    # corpus on every question (same reasoning as app.py's @st.cache_resource).
    # miss_log is kept alongside QA (not reached via QA's private _miss_log) so
    # /knowledge-gaps can read it without poking at QA's internals.
    app.state.qa, app.state.miss_log = _build_qa()
    yield


app = FastAPI(lifespan=lifespan)
app.add_middleware(
    CORSMiddleware,
    allow_origins=[FRONTEND_ORIGIN],
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)


class AskRequest(BaseModel):
    employee_id: str
    question: str
    start_date: date | None = None
    as_of: date | None = None
    # PLAN_PR15 D1/D2: short code from the frontend's EN/DE toggle ("de" or
    # absent/None — English is the default, no instruction needed). Corpus and
    # citations stay English; only the generated answer's language changes.
    language: str | None = None


class Citation(BaseModel):
    documentId: str
    title: str
    excerpt: str


class HandoffInfo(BaseModel):
    department: str
    person: str
    email: str


class GroundedAnswer(BaseModel):
    status: str  # "SUPPORTED" | "NEEDS_HUMAN"
    answer: str
    citations: list[Citation]
    handoff: HandoffInfo | None = None
    # PLAN_PR14 B4: short "asked at" chip, e.g. "T-40 · 2-8 weeks out" — None when
    # QA had no start_date to band against (Answer.asked_at's own None case).
    askedAt: str | None = None


_EXCERPT_LENGTH = 220


def _truncate(text: str) -> str:
    return text if len(text) <= _EXCERPT_LENGTH else text[:_EXCERPT_LENGTH].rsplit(" ", 1)[0] + "…"


# PLAN_PR15 B1's second trap: the handoff sentence is templated here, not
# generated by the model, so B1's language toggle would otherwise leave a German
# question ending in an English handoff — worse than staying all-English. This is
# a fixed sentence with one blank, so a static translation is cheap and doesn't
# need an FM call; `department`/`person`/`email` on HandoffInfo stay as-is either
# way, since those are data, not narration.
_HANDOFF_TEMPLATES = {
    "de": (
        "Ich bin mir dabei nicht sicher genug, um das anhand der verfügbaren "
        "Dokumente zu beantworten. Ich habe es daher an {who} weitergeleitet — "
        "von dort meldet sich jemand direkt bei dir."
    ),
}


def _handoff_response(target, language: str | None = None) -> GroundedAnswer:
    who = target.department or target.name
    template = _HANDOFF_TEMPLATES.get(language or "")
    answer = (
        template.format(who=who)
        if template
        else "I'm not confident enough to answer that from the available documents, so "
        f"I've flagged it for {who}, who will follow up with you directly."
    )
    return GroundedAnswer(
        status="NEEDS_HUMAN",
        answer=answer,
        citations=[],
        handoff=HandoffInfo(department=who, person=target.name, email=target.contact),
    )


@app.post("/ask")
def ask(req: AskRequest) -> GroundedAnswer:
    qa: QA = app.state.qa
    try:
        result = qa.ask(
            req.employee_id,
            req.question,
            start_date=req.start_date,
            as_of=req.as_of,
            language=req.language,
        )
    except Exception as exc:  # noqa: BLE001 — degrade to a handoff, never a 500 traceback (app.py's pattern)
        print(f"[server] error answering question for {req.employee_id!r}: {exc!r}")
        return _handoff_response(handoff_target(req.employee_id), req.language)

    if isinstance(result, Answer):
        return GroundedAnswer(
            status="SUPPORTED",
            answer=result.text,
            citations=[
                Citation(
                    documentId=c.source_doc,
                    title=c.title or c.source_doc,
                    excerpt=_truncate(c.excerpt or c.source_section),
                )
                for c in result.citations
            ],
            askedAt=result.asked_at,
        )

    assert isinstance(result, Handoff)
    return _handoff_response(result.target, req.language)


@app.get("/health")
def health() -> dict:
    return {"real_components": has_databricks_credentials()}


class DepartmentGap(BaseModel):
    department: str
    count: int
    distinctQuestions: int
    distinctOffers: int
    lastSeen: str


class QuestionGap(BaseModel):
    question: str
    department: str | None
    count: int
    distinctOffers: int
    lastSeen: str


class CountdownGap(BaseModel):
    bucket: str
    count: int
    distinctQuestions: int
    distinctOffers: int
    lastSeen: str


class KnowledgeGaps(BaseModel):
    departments: list[DepartmentGap]
    questions: list[QuestionGap]
    # PLAN_PR14 B5: where on candidates' countdowns misses land, chronologically
    # ordered (see preboard.gap_report.countdown_gap_report), not count-descending.
    countdown: list[CountdownGap]


@app.get("/knowledge-gaps")
def knowledge_gaps() -> KnowledgeGaps:
    """Backs `frontend`'s HR "Knowledge gaps" panel (ported from
    `feature/fused-preboard`) — the same `question_misses` data `?view=gaps` in
    `app.py` and `gap_report.main()` already show, just as JSON. No HR/candidate
    scoping here: that's the Next.js route's job (`readSession`/`hasCapability`),
    matching how `/ask` leaves auth to the caller (NOTES.md §19, D3)."""
    from preboard.gap_report import countdown_gap_report, department_gap_report, gap_report

    miss_log = app.state.miss_log
    return KnowledgeGaps(
        departments=[
            DepartmentGap(
                department=d.department,
                count=d.count,
                distinctQuestions=d.distinct_questions,
                distinctOffers=d.distinct_offers,
                lastSeen=d.last_seen,
            )
            for d in department_gap_report(miss_log)
        ],
        questions=[
            QuestionGap(
                question=q.example_question,
                department=q.department,
                count=q.count,
                distinctOffers=q.distinct_offers,
                lastSeen=q.last_seen,
            )
            for q in gap_report(miss_log, top_n=20)
        ],
        countdown=[
            CountdownGap(
                bucket=c.bucket,
                count=c.count,
                distinctQuestions=c.distinct_questions,
                distinctOffers=c.distinct_offers,
                lastSeen=c.last_seen,
            )
            for c in countdown_gap_report(miss_log)
        ],
    )


class DraftRequest(BaseModel):
    question: str
    department: str


class DraftResponse(BaseModel):
    draft: str
    department: str


@app.post("/draft-section")
def draft_section_endpoint(req: DraftRequest) -> DraftResponse:
    """PLAN_PR15 B6: drafts a proposed handbook paragraph for a gap-report row, HR-
    triggered per row (D5) — never fired automatically on page load, and never
    reaches a candidate. See `preboard/drafting.py` for why this is a separate
    code path from `QA.ask`/`Generator.generate`, not a variant of either."""
    import os  # noqa: PLC0415

    if not has_databricks_credentials():
        return DraftResponse(
            draft="Draft generation needs Databricks credentials, which aren't configured in this environment.",
            department=req.department,
        )
    from preboard.drafting import draft_section  # noqa: PLC0415

    endpoint_name = os.environ.get(FM_ENDPOINT_ENV, DEFAULT_FM_ENDPOINT)
    return DraftResponse(
        draft=draft_section(req.question, req.department, endpoint_name),
        department=req.department,
    )
